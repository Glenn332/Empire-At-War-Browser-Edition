export function animKinds(base, names) {
  const have = names instanceof Set ? names : new Set(names);
  const kinds = new Map();
  for (const suffix of ANIM_SUFFIXES) {
    const list = [];
    for (let i = 0; i < 100; i++) {
      const name = `${base}_${suffix}_${String(i).padStart(2, '0')}.ALA`;
      if (!have.has(name)) break;
      list.push(name);
    }
    if (list.length) kinds.set(suffix, list);
  }
  return kinds;
}
